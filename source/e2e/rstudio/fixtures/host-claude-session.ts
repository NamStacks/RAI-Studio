import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

/**
 * Live Claude tests WITHOUT copying credentials into the sandbox.
 *
 * Opt-in with PW_AI_CLAUDE_HOST_SESSION=1 and PW_AI_CLAUDE_HOST_CWD=<dir>.
 *
 * The Claude CLI keeps its OAuth session in the macOS login Keychain, keyed to
 * the real HOME. Instead of copying ~/.claude/.credentials.json into the
 * sandbox (PW_SEED_AI_CREDENTIALS), this mode points the sandbox's RAI
 * Assistant profile at a small launcher that starts the host CLI with the
 * real HOME, inside a dedicated EMPTY working directory that the operator has
 * already trusted. Nothing is copied or written to the host's auth state; the
 * sandbox holds only the launcher and its assistant.json.
 *
 * `--setting-sources project,local` keeps the host's user-level hooks and
 * settings out of the test session; the dedicated cwd has no project or local
 * settings, so the session runs with the CLI's built-in defaults plus the
 * bridge's own session flags.
 *
 * Excluding user settings also drops the user's `theme`, and a CLI update can
 * add a first-run feature prompt (live-claude-rc2-2: Claude 2.1.283 stopped at
 * a "Choose the text style" picker, and at a Claude-in-Chrome opt-in when a
 * theme was set). Both are interactive screens that swallow the test prompt.
 * HOST_SESSION_FLAGS pins a theme through a session-only --settings value and
 * declines Chrome for this session only. Nothing is written to host config.
 */
export const HOST_SESSION_FLAGS: readonly string[] = [
  '--setting-sources', 'project,local',
  '--settings', '{"theme":"dark"}',
  '--no-chrome',
];

export function hostClaudeSessionRequested(): boolean {
  return ['1', 'true'].includes((process.env.PW_AI_CLAUDE_HOST_SESSION ?? '').toLowerCase());
}

export function hostClaudeCliPath(): string {
  const candidates = [
    process.env.PW_AI_CLAUDE_HOST_CLI,
    path.join(os.homedir(), '.local', 'bin', 'claude'),
    '/opt/homebrew/bin/claude',
    '/usr/local/bin/claude',
  ].filter((p): p is string => !!p);
  const found = candidates.find((p) => path.isAbsolute(p) && fs.existsSync(p));
  if (!found) throw new Error('[host-claude] no claude CLI found (set PW_AI_CLAUDE_HOST_CLI)');
  return found;
}

/** Pure: launcher script text. Exported for the unit regression. */
export function hostClaudeLauncher(opts: { realHome: string; cwd: string; cli: string }): string {
  const q = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
  return [
    '#!/bin/sh',
    '# Generated by e2e host-claude-session: host CLI, real HOME, dedicated trusted cwd.',
    `cd ${q(opts.cwd)} || exit 97`,
    `HOME=${q(opts.realHome)}; export HOME`,
    `exec ${q(opts.cli)} ${HOST_SESSION_FLAGS.map(q).join(' ')} "$@"`,
    '',
  ].join('\n');
}

export function setupHostClaudeSession(userHome: string): void {
  const cwd = process.env.PW_AI_CLAUDE_HOST_CWD ?? '';
  if (!cwd || !path.isAbsolute(cwd) || !fs.existsSync(cwd) || !fs.statSync(cwd).isDirectory()) {
    throw new Error('[host-claude] PW_AI_CLAUDE_HOST_CWD must be an existing absolute directory');
  }
  if (fs.readdirSync(cwd).length !== 0) {
    throw new Error(`[host-claude] ${cwd} must be empty (dedicated test workspace)`);
  }
  const realHome = os.homedir();
  if (path.resolve(userHome) === path.resolve(realHome)) {
    throw new Error('[host-claude] sandbox user-home must not be the real HOME');
  }
  const cli = hostClaudeCliPath();

  // Read-only probe of the existing login (no login flow is ever started).
  const status = JSON.parse(execFileSync(cli, ['auth', 'status'], {
    cwd, env: { ...process.env, HOME: realHome }, encoding: 'utf8', timeout: 30000,
  }));
  if (status.loggedIn !== true) {
    console.log('[host-claude] host Claude CLI is not logged in; @ai claude tests will skip');
    return;
  }
  // Trust must already exist (operator-granted); this harness never writes it.
  const claudeJson = JSON.parse(fs.readFileSync(path.join(realHome, '.claude.json'), 'utf8'));
  if (claudeJson?.projects?.[cwd]?.hasTrustDialogAccepted !== true) {
    throw new Error(`[host-claude] ${cwd} is not trusted in ~/.claude.json; grant trust first`);
  }

  const binDir = path.join(userHome, '.rai-e2e-bin');
  fs.mkdirSync(binDir, { recursive: true });
  const launcher = path.join(binDir, 'claude-host-session');
  fs.writeFileSync(launcher, hostClaudeLauncher({ realHome, cwd, cli }), { mode: 0o700 });

  const raiDir = path.join(userHome, '.raistudio');
  fs.mkdirSync(raiDir, { recursive: true });
  fs.writeFileSync(path.join(raiDir, 'assistant.json'), JSON.stringify({
    provider: 'claude', model: '', effort: '', caffeinate: false, autoApproveReadOnly: true,
    providers: { claude: { command: launcher, args: [], modelFlag: '--model', authMode: 'subscription' } },
  }, null, 2));

  process.env.PW_AI_SEEDED_CLAUDE = '1';
  console.log(`[host-claude] using host Claude session (authMethod=${status.authMethod}); no credentials copied`);
}
