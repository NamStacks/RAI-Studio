test_that("autonomy snippet edits refuse an unread code buffer before cards or requests", {
   fx <- aut_fixture()
   old_documents <- aut_get(".rs.rai.listOpenDocuments")
   old_read <- aut_get(".rs.rai.documentReadDigest")
   withr::defer({
      aut_set(".rs.rai.listOpenDocuments", old_documents)
      aut_set(".rs.rai.documentReadDigest", old_read)
   })
   aut_set(".rs.rai.listOpenDocuments", aut_open_documents())
   aut_set(".rs.rai.documentReadDigest", function(documentId) "")
   refused <- aut_get(".rs.rai.queueDocumentEdit")("doc-auto", "x <- 1", "x <- 2")
   expect_identical(refused$status, "error")
   expect_identical(refused$policy, "refused")
   expect_identical(refused$message, "read whole file first / file changed since read")
   expect_length(fx$events$items, 0L)
   expect_length(ls(aut_get(".rs.rai.grantState")$requests, all.names = TRUE), 0L)
   aut_read_document_fixture("doc-auto", "x <- 1")
   accepted <- aut_get(".rs.rai.queueDocumentEdit")("doc-auto", "x <- 1", "x <- 2")
   expect_identical(accepted$status, "applying")
   expect_length(fx$events$items, 1L)
})
